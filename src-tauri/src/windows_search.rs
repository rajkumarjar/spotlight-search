use std::mem::{offset_of, size_of};
use std::ptr;

use windows::core::{w, IUnknown, Interface, GUID, PCWSTR};
use windows::Win32::System::Com::{
    CoCreateInstance, CoInitializeEx, CoTaskMemFree, CoUninitialize, CLSCTX_INPROC_SERVER,
    CLSCTX_LOCAL_SERVER, COINIT_MULTITHREADED,
};
use windows::Win32::System::Search::{
    CSearchManager, IAccessor, ICommandText, IDBCreateCommand, IDBCreateSession, IDBInitialize,
    IDataInitialize, IRowset, DBACCESSOR_ROWDATA, DBBINDING, DBMEMOWNER_CLIENTOWNED,
    DBPARAMIO_NOTPARAM, DBPART_LENGTH, DBPART_STATUS, DBPART_VALUE, DBSTATUS_S_OK, DBTYPE_BOOL,
    DBTYPE_WSTR, HACCESSOR, MSDAINITIALIZE,
};

use nucleo_matcher::pattern::{CaseMatching, Normalization, Pattern};
use nucleo_matcher::{Config, Matcher, Utf32Str};

use crate::search::SearchResult;

const DBGUID_DEFAULT: GUID = GUID::from_u128(0xc8b521fb_5cf3_11ce_ade5_00aa0044773d);
const RESULT_LIMIT: usize = 64;
const BATCH: usize = 16;
const NAME_UNITS: usize = 512;
const PATH_UNITS: usize = 1024;

pub fn search(query: &str, limit: usize) -> Result<Vec<(i64, SearchResult)>, String> {
    if query.trim().is_empty() {
        return Ok(Vec::new());
    }
    let _apartment = ComApartment::initialize()?;

    // SAFETY: Activates the documented Windows Search COM server in this thread's
    // initialized COM apartment.
    let manager: windows::Win32::System::Search::ISearchManager =
        unsafe { CoCreateInstance(&CSearchManager, None, CLSCTX_LOCAL_SERVER) }
            .map_err(|error| format!("activate Windows Search Manager: {error}"))?;
    // SAFETY: "SystemIndex" is a static, NUL-terminated catalog name.
    let catalog = unsafe { manager.GetCatalog(w!("SystemIndex")) }
        .map_err(|error| format!("open SystemIndex catalog: {error}"))?;
    // SAFETY: Query helper is returned by the catalog and owned by this scope.
    let helper = unsafe { catalog.GetQueryHelper() }
        .map_err(|error| format!("create Windows Search query helper: {error}"))?;
    // SAFETY: Property lists and limits are static query configuration.
    unsafe {
        helper.SetQuerySelectColumns(w!(
            "System.ItemNameDisplay,System.ItemPathDisplay,System.IsFolder"
        ))
    }
    .map_err(|error| format!("configure Windows Search result columns: {error}"))?;
    // Limit the content search to filenames; file contents are not read or sent
    // outside the machine.
    unsafe { helper.SetQueryContentProperties(w!("System.ItemNameDisplay")) }
        .map_err(|error| format!("configure Windows Search name search: {error}"))?;
    unsafe { helper.SetQueryMaxResults(limit.min(RESULT_LIMIT) as i32) }
        .map_err(|error| format!("configure Windows Search result limit: {error}"))?;
    let wide_query: Vec<u16> = query.encode_utf16().chain(Some(0)).collect();
    // SAFETY: Query text is NUL-terminated and remains alive for the call.
    let sql = unsafe { helper.GenerateSQLFromUserQuery(PCWSTR(wide_query.as_ptr())) }
        .map_err(|error| format!("generate Windows Search SQL: {error}"))?;
    let sql_text = unsafe { sql.to_string() }.map_err(|error| error.to_string())?;
    // SAFETY: `sql` is the COM-allocated string returned above.
    unsafe { CoTaskMemFree(Some(sql.as_ptr().cast())) };

    // SAFETY: Activates the documented OLE DB data initialization component.
    let initializer: IDataInitialize =
        unsafe { CoCreateInstance(&MSDAINITIALIZE, None, CLSCTX_INPROC_SERVER) }
            .map_err(|error| format!("activate OLE DB initializer: {error}"))?;
    // SAFETY: Connection string is generated by the Windows Search query helper.
    let connection = unsafe { helper.ConnectionString() }
        .map_err(|error| format!("get Windows Search connection string: {error}"))?;
    let mut source: Option<IUnknown> = None;
    // SAFETY: COM out pointer is initialized and remains owned by this frame.
    unsafe {
        initializer.GetDataSource(
            None,
            CLSCTX_INPROC_SERVER.0,
            PCWSTR(connection.as_ptr()),
            &IDBInitialize::IID,
            &mut source,
        )
    }
    .map_err(|error| format!("connect to Search.CollatorDSO: {error}"))?;
    // SAFETY: Frees the connection string allocated by the helper.
    unsafe { CoTaskMemFree(Some(connection.as_ptr().cast())) };
    let source =
        source.ok_or_else(|| "Windows Search returned no OLE DB data source.".to_owned())?;
    let initialize: IDBInitialize = source
        .cast()
        .map_err(|error| format!("get Windows Search initializer interface: {error}"))?;
    // SAFETY: Initializes the OLE DB source returned by the Windows Search provider.
    unsafe { initialize.Initialize() }
        .map_err(|error| format!("initialize Search.CollatorDSO: {error}"))?;
    let sessions: IDBCreateSession = initialize
        .cast()
        .map_err(|error| format!("get Windows Search session interface: {error}"))?;
    // SAFETY: Creates a command session and requests the corresponding interface.
    let session = unsafe { sessions.CreateSession(None, &IDBCreateCommand::IID) }
        .map_err(|error| format!("create Windows Search session: {error}"))?;
    let commands: IDBCreateCommand = session
        .cast()
        .map_err(|error| format!("get Windows Search command interface: {error}"))?;
    // SAFETY: Creates a command and requests ICommandText.
    let command = unsafe { commands.CreateCommand(None, &ICommandText::IID) }
        .map_err(|error| format!("create Windows Search command: {error}"))?;
    let text: ICommandText = command
        .cast()
        .map_err(|error| format!("get Windows Search command text interface: {error}"))?;
    let wide_sql: Vec<u16> = sql_text.encode_utf16().chain(Some(0)).collect();
    // SAFETY: SQL is NUL-terminated and stays alive for the duration of the call.
    unsafe { text.SetCommandText(&DBGUID_DEFAULT, PCWSTR(wide_sql.as_ptr())) }
        .map_err(|error| format!("set Windows Search SQL: {error}"))?;
    let mut rowset: Option<IUnknown> = None;
    // SAFETY: No command parameters are used; rowset is a valid COM out parameter.
    unsafe {
        text.Execute::<Option<&IUnknown>>(None, &IRowset::IID, None, None, Some(&mut rowset))
    }
    .map_err(|error| format!("execute Windows Search query: {error}"))?;
    let rowset: IRowset = rowset
        .ok_or_else(|| "Windows Search returned no result set.".to_owned())?
        .cast()
        .map_err(|error| format!("get Windows Search rowset: {error}"))?;
    let accessor_factory: IAccessor = rowset
        .cast()
        .map_err(|error| format!("get Windows Search row accessor: {error}"))?;
    let bindings = row_bindings();
    let mut accessor = HACCESSOR(0);
    let mut binding_status = [0_u32; 3];
    // SAFETY: Bindings describe the fields of SearchRow and the exact row size.
    unsafe {
        accessor_factory.CreateAccessor(
            DBACCESSOR_ROWDATA.0 as u32,
            bindings.len(),
            bindings.as_ptr(),
            size_of::<SearchRow>(),
            &mut accessor,
            Some(binding_status.as_mut_ptr()),
        )
    }
    .map_err(|error| format!("bind Windows Search result columns {binding_status:?}: {error}"))?;
    let mut rows = vec![SearchRow::default(); BATCH];
    let mut output = Vec::new();
    let pattern = Pattern::parse(query, CaseMatching::Ignore, Normalization::Smart);
    let mut matcher = Matcher::new(Config::DEFAULT);
    let mut utf32_buffer = Vec::new();

    loop {
        let mut handles = [ptr::null_mut::<usize>(); BATCH];
        let mut obtained = 0;
        // SAFETY: Handles and count are output buffers; the slice is BATCH long.
        unsafe { rowset.GetNextRows(0, 0, &mut obtained, &mut handles) }
            .map_err(|error| format!("fetch Windows Search rows: {error}"))?;
        if obtained == 0 {
            break;
        }

        let allocation = handles[0];
        for (index, row) in rows.iter_mut().take(obtained).enumerate() {
            // SAFETY: Provider allocated `allocation` to contain `obtained` handles.
            let handle = unsafe { *allocation.add(index) };
            // SAFETY: The row buffer has the exact size passed to CreateAccessor.
            if unsafe { rowset.GetData(handle, accessor, (row as *mut SearchRow).cast()) }.is_ok() {
                if let Some((name, path, is_folder)) = row.fields() {
                    let score = pattern
                        .score(Utf32Str::new(&name, &mut utf32_buffer), &mut matcher)
                        .map(i64::from)
                        .unwrap_or_else(|| 500 - output.len() as i64);
                    let mut id = if is_folder { "folder:" } else { "file:" }.to_owned();
                    id.push_str(&path);
                    output.push((
                        score,
                        SearchResult {
                            id,
                            name,
                            subtitle: path,
                            kind: if is_folder { "Folder" } else { "File" }.to_owned(),
                        },
                    ));
                }
            }
        }

        // SAFETY: Releases provider row handles and its matching task allocation.
        unsafe {
            let _ = rowset.ReleaseRows(
                obtained,
                allocation.cast_const(),
                ptr::null(),
                ptr::null_mut(),
                ptr::null_mut(),
            );
            CoTaskMemFree(Some(allocation.cast()));
        }
        if obtained < BATCH || output.len() >= limit.min(RESULT_LIMIT) {
            break;
        }
    }

    // SAFETY: Releases the accessor created above.
    let _ = unsafe { accessor_factory.ReleaseAccessor(accessor, None) };
    Ok(output)
}

fn row_bindings() -> [DBBINDING; 3] {
    [
        make_binding(
            1,
            offset_of!(SearchRow, name),
            offset_of!(SearchRow, name_length),
            offset_of!(SearchRow, name_status),
            size_of::<[u16; NAME_UNITS]>(),
            DBTYPE_WSTR.0 as u16,
        ),
        make_binding(
            2,
            offset_of!(SearchRow, path),
            offset_of!(SearchRow, path_length),
            offset_of!(SearchRow, path_status),
            size_of::<[u16; PATH_UNITS]>(),
            DBTYPE_WSTR.0 as u16,
        ),
        make_binding(
            3,
            offset_of!(SearchRow, is_folder),
            offset_of!(SearchRow, is_folder_length),
            offset_of!(SearchRow, is_folder_status),
            size_of::<i16>(),
            DBTYPE_BOOL.0 as u16,
        ),
    ]
}

fn make_binding(
    ordinal: usize,
    value: usize,
    length: usize,
    status: usize,
    size: usize,
    data_type: u16,
) -> DBBINDING {
    DBBINDING {
        iOrdinal: ordinal,
        obValue: value,
        obLength: length,
        obStatus: status,
        dwPart: (DBPART_VALUE.0 | DBPART_LENGTH.0 | DBPART_STATUS.0) as u32,
        dwMemOwner: DBMEMOWNER_CLIENTOWNED.0 as u32,
        eParamIO: DBPARAMIO_NOTPARAM.0 as u32,
        cbMaxLen: size,
        wType: data_type,
        ..Default::default()
    }
}

#[repr(C)]
#[derive(Clone)]
struct SearchRow {
    name: [u16; NAME_UNITS],
    name_status: u32,
    name_length: usize,
    path: [u16; PATH_UNITS],
    path_status: u32,
    path_length: usize,
    is_folder: i16,
    is_folder_status: u32,
    is_folder_length: usize,
}

impl Default for SearchRow {
    fn default() -> Self {
        Self {
            name: [0; NAME_UNITS],
            name_status: 0,
            name_length: 0,
            path: [0; PATH_UNITS],
            path_status: 0,
            path_length: 0,
            is_folder: 0,
            is_folder_status: 0,
            is_folder_length: 0,
        }
    }
}

impl SearchRow {
    fn fields(&self) -> Option<(String, String, bool)> {
        if self.name_status != DBSTATUS_S_OK.0 as u32
            || self.path_status != DBSTATUS_S_OK.0 as u32
            || self.is_folder_status != DBSTATUS_S_OK.0 as u32
        {
            return None;
        }
        let name_length = (self.name_length / size_of::<u16>()).min(self.name.len());
        let path_length = (self.path_length / size_of::<u16>()).min(self.path.len());
        let name_length = self.name[..name_length]
            .iter()
            .position(|unit| *unit == 0)
            .unwrap_or(name_length);
        let path_length = self.path[..path_length]
            .iter()
            .position(|unit| *unit == 0)
            .unwrap_or(path_length);
        if name_length == 0 || path_length == 0 {
            return None;
        }
        Some((
            String::from_utf16_lossy(&self.name[..name_length]),
            String::from_utf16_lossy(&self.path[..path_length]),
            self.is_folder != 0,
        ))
    }
}

struct ComApartment;

impl ComApartment {
    fn initialize() -> Result<Self, String> {
        // SAFETY: This command creates a dedicated blocking worker thread and
        // balances successful COM initialization in Drop.
        unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) }
            .ok()
            .map(|_| Self)
            .map_err(|error| error.to_string())
    }
}

impl Drop for ComApartment {
    fn drop(&mut self) {
        // SAFETY: This balances the successful CoInitializeEx call above.
        unsafe { CoUninitialize() };
    }
}

#[cfg(test)]
mod tests {
    use super::{SearchRow, DBSTATUS_S_OK};

    #[test]
    fn decodes_a_folder_search_result() {
        let name: Vec<u16> = "Downloads".encode_utf16().collect();
        let path: Vec<u16> = "C:\\Users\\User\\Downloads".encode_utf16().collect();
        let mut row = SearchRow::default();
        row.name[..name.len()].copy_from_slice(&name);
        row.name_length = name.len() * std::mem::size_of::<u16>();
        row.name_status = DBSTATUS_S_OK.0 as u32;
        row.path[..path.len()].copy_from_slice(&path);
        row.path_length = path.len() * std::mem::size_of::<u16>();
        row.path_status = DBSTATUS_S_OK.0 as u32;
        row.is_folder = -1;
        row.is_folder_status = DBSTATUS_S_OK.0 as u32;

        assert_eq!(
            row.fields(),
            Some((
                "Downloads".to_owned(),
                "C:\\Users\\User\\Downloads".to_owned(),
                true
            ))
        );
    }
}
